# Blender (background) tool: derive a camper's walkable floor from its meshes.
#
#   blender -b --factory-startup --python floorplan.py -- <config.json>
#
# The config names the FBX, the mesh objects that block walking, how Blender's world
# coordinates map to the game's passenger space (tiles), the floor height and the
# character radius. The tool casts rays straight down from head height over a grid:
# a cell is free when the first surface it meets is the floor. Free space is then
# shrunk by the character radius. It writes a Lua walk grid for the profile and a PNG
# (free = light, blocked = dark, marked points in colour) to check it by eye.
import json
import math
import sys

import bpy
from mathutils import Vector
from mathutils.bvhtree import BVHTree

args = sys.argv[sys.argv.index("--") + 1:]
with open(args[0], "r", encoding="utf-8-sig") as handle:
    cfg = json.load(handle)

bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.fbx(filepath=cfg["fbx"])

m = cfg["map"]  # passenger = sign * scale * blender axis
def to_blender(px, py, pz):
    return Vector((px / (m["sx"]), pz / (m["sz"]), py / (m["sy"])))

trees = []
depsgraph = bpy.context.evaluated_depsgraph_get()
for name in cfg["objects"]:
    obj = bpy.data.objects.get(name)
    if obj is None:
        raise SystemExit("missing object " + name)
    mesh = obj.evaluated_get(depsgraph).to_mesh()
    verts = [obj.matrix_world @ v.co for v in mesh.vertices]
    polys = [tuple(p.vertices) for p in mesh.polygons]
    trees.append(BVHTree.FromPolygons(verts, polys))

floor_y = cfg["floorY"]
cell = cfg["cell"]
x0, x1 = cfg["xRange"]
z0, z1 = cfg["zRange"]
cols = int(round((x1 - x0) / cell))
rows = int(round((z1 - z0) / cell))
head = floor_y + cfg.get("headroom", 1.05)
bottom = floor_y - 0.25
tolerance = cfg.get("floorTolerance", 0.06)

free = [[False] * cols for _ in range(rows)]
height = [[None] * cols for _ in range(rows)]
down = Vector((0.0, 0.0, -1.0))
for r in range(rows):
    pz = z0 + (r + 0.5) * cell
    for c in range(cols):
        px = x0 + (c + 0.5) * cell
        origin = to_blender(px, head, pz)
        reach = (head - bottom) / abs(m["sy"])
        best = None
        for tree in trees:
            hit = tree.ray_cast(origin, down, reach)
            if hit[0] is not None and (best is None or hit[3] < best[3]):
                best = hit
        if best is None:
            continue
        hy = best[0].z * m["sy"]
        height[r][c] = hy
        free[r][c] = abs(hy - floor_y) <= tolerance

# Shrink free space by the character radius (a cell stays free only if every cell
# within the radius is free).
radius_cells = int(math.ceil(cfg["radius"] / cell))
offsets = [(dr, dc) for dr in range(-radius_cells, radius_cells + 1)
           for dc in range(-radius_cells, radius_cells + 1)
           if (dr * dr + dc * dc) * cell * cell <= cfg["radius"] ** 2]
walk = [[False] * cols for _ in range(rows)]
for r in range(rows):
    for c in range(cols):
        if not free[r][c]:
            continue
        ok = True
        for dr, dc in offsets:
            rr, cc = r + dr, c + dc
            if rr < 0 or rr >= rows or cc < 0 or cc >= cols or not free[rr][cc]:
                ok = False
                break
        walk[r][c] = ok

# Points to check (door, stand points): report whether they are walkable.
report = []
for label, (px, pz) in cfg.get("points", {}).items():
    c = int((px - x0) / cell)
    r = int((pz - z0) / cell)
    inside = 0 <= r < rows and 0 <= c < cols
    report.append("%s (%.2f, %.2f): %s" % (label, px, pz,
        "walkable" if inside and walk[r][c] else ("floor" if inside and free[r][c] else "BLOCKED")))

# Lua walk grid: one string per row (z), '1' walkable.
lines = ["-- Generated by tools-src/blender/floorplan.py from " + cfg["name"] + "; do not edit.",
         "MELens = MELens or {}",
         "MELens.WalkGrids = MELens.WalkGrids or {}",
         "MELens.WalkGrids[%s] = {" % json.dumps(cfg["name"]),
         "    x0 = %.4f, z0 = %.4f, cell = %.4f, cols = %d, rows = {" % (x0, z0, cell, cols)]
for r in range(rows):
    lines.append('        "%s",' % "".join("1" if walk[r][c] else "0" for c in range(cols)))
lines.append("    },")
lines.append("}")
with open(cfg["luaOut"], "w", encoding="utf-8", newline="\n") as handle:
    handle.write("\n".join(lines) + "\n")

# PNG: a top-down view with the front (+z) at the top and the camper's left (+x) on the left.
scale = cfg.get("pngScale", 4)
w, h = cols * scale, rows * scale
img = bpy.data.images.new("floorplan", width=w, height=h)
pixels = [0.0] * (w * h * 4)
def put(x, y, rgb):
    i = (y * w + x) * 4
    pixels[i:i + 4] = [rgb[0], rgb[1], rgb[2], 1.0]
for r in range(rows):
    for c in range(cols):
        if walk[r][c]:
            rgb = (0.85, 0.85, 0.8)
        elif free[r][c]:
            rgb = (0.55, 0.55, 0.5)
        elif height[r][c] is None:
            rgb = (0.05, 0.05, 0.1)
        else:
            t = max(0.0, min(1.0, (height[r][c] - floor_y) / 1.0))
            rgb = (0.35 + 0.4 * t, 0.2, 0.15)
        # grid lines every 0.5 tiles
        px = x0 + c * cell
        pz = z0 + r * cell
        on_line = abs(px / 0.5 - round(px / 0.5)) < cell / 0.5 / 2 or abs(pz / 0.5 - round(pz / 0.5)) < cell / 0.5 / 2
        if on_line:
            rgb = (rgb[0] * 0.7, rgb[1] * 0.7, rgb[2] * 0.9)
        for dy in range(scale):
            for dx in range(scale):
                put((cols - 1 - c) * scale + dx, r * scale + dy, rgb)
for label, (px, pz) in cfg.get("points", {}).items():
    c = int((px - x0) / cell)
    r = int((pz - z0) / cell)
    for dy in range(-2 * scale, 2 * scale):
        for dx in range(-2 * scale, 2 * scale):
            x, y = (cols - 1 - c) * scale + dx, r * scale + dy
            if 0 <= x < w and 0 <= y < h:
                put(x, y, (0.1, 0.8, 0.2) if label.startswith("door") else (0.2, 0.4, 1.0))
img.pixels = pixels
img.filepath_raw = cfg["pngOut"]
img.file_format = "PNG"
img.save()

print("FLOORPLAN %s: %d x %d cells of %.3f tiles, walkable %d, floor %d" % (
    cfg["name"], cols, rows, cell,
    sum(sum(1 for v in row if v) for row in walk), sum(sum(1 for v in row if v) for row in free)))
for line in report:
    print("POINT " + line)
