"""Generate the explicitly measured expansion families and their shared-model declarations."""
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_vehicles as mv

ROOT = Path(mv.ROOT)
OUT = ROOT / 'build/rv/floorplans'

# Every supported body uses native walls. Plain inward repaint belongs to stock
# vehicles; KI5 keeps the first curved-wall treatment approved on E150 and F350.
PLAIN_WALL_FAMILIES = frozenset({
    'VanillaVan', 'VanillaPassengerVan', 'VanillaAmbulance',
    'VanillaRadioVan', 'VanillaStepVan',
})

# Rendered rear tyres include model offsets and suspension that the script's
# physics radius omits. Clearances measured with the native body-space survey,
# then reviewed in the game (inner side, half length, height above the floor).
REAR_ARCH = {
    'VanillaVan': (.43, .40, .22), 'VanillaPassengerVan': (.43, .40, .22),
    'VanillaAmbulance': (.43, .40, .22), 'VanillaRadioVan': (.43, .40, .22),
    'VanillaStepVan': (.43, .42, .19),
    'E150Short': (.60, .37, .16), 'E150Long': (.60, .37, .16), 'E150Windows': (.60, .37, .16),
    'ChevyStepVan': (.47, .42, .14), 'F700Bank': (.46, .52, .15),
    'F700Swat': (.46, .52, .15), 'F350Ambulance': (.53, .42, .15),
}


def main():
    rows = json.loads((OUT / 'fleet-measures.json').read_text())
    catalogue = {entry['fullName']: entry for entry in json.loads((ROOT / 'build/rv/vehicle-catalogue.json').read_text())['entries']}
    surface_cuts = json.loads((ROOT / 'tools-src/vehicles/native-interior-cuts.json').read_text())['families']
    cab_partitions = json.loads((ROOT / 'tools-src/vehicles/native-cab-partitions.json').read_text())['families']
    declarations = ['/* Generated by tools-src/vehicles/build_expansion.py. Uses existing authored materials. */', 'module Base', '{']
    coverage = []
    for row in rows:
        key = row['key']
        spec_path = ROOT / f'tools-src/vehicles/specs/{key}.json'
        existing_spec = mv.load(str(spec_path)) if spec_path.exists() else {}
        measure = mv.load(str(OUT / f'measure_{key}.json'))
        info = mv.load(str(OUT / row['scripts'][0]))[row['scripts'][1]]
        scale = info['model']['scale']
        floor, ceiling = round(measure['floor'] + .012, 3), measure['ceiling']
        assert ceiling - floor >= .95, (key, 'insufficient headroom')
        rear = round(measure['body']['min'][2] + .16, 3)
        front = round(row['sampleZ'][1] - .04, 3)
        visual_front = cab_partitions.get(key, {}).get('cutFront', front)
        assert front - rear >= 2.0, (key, 'compartment too short')
        half = min(abs(measure['body']['min'][0]), abs(measure['body']['max'][0])) - .075
        # Fit a conservative rectangular lining inside the measured upper body.
        # Ignore missing sections at windows, but never widen to the physics box.
        widths = []
        for h in (floor + .4, min(ceiling - .04, floor + mv.FURNITURE_TOP)):
            sections = measure['sections'][min(measure['sections'], key=lambda k: abs(float(k) - h))]
            for t in (.12, .3, .5, .7, .88):
                z = rear + (front - rear) * t
                cross = []
                for a, b in sections:
                    if (a[1] - z) * (b[1] - z) <= 0 and a[1] != b[1]:
                        cross.append(a[0] + (b[0] - a[0]) * (z - a[1]) / (b[1] - a[1]))
                negative, positive = [x for x in cross if x < 0], [x for x in cross if x > 0]
                if negative and positive:
                    widths.append(min(abs(min(negative)), max(positive)) - .035)
        if widths:
            half = min(half, min(widths))
        assert half >= .56, (key, 'body is too narrow', half)
        half = round(min(.98, half), 3)
        wells = []
        for wheel in info.get('wheelGeometry', {}).values():
            x, y, z = [v * scale for v in wheel['offset']]
            if x <= 0 or not rear + .4 < z < front - .4:
                continue
            assert wheel['radius'] and wheel['width'], (key, 'missing wheel dimensions')
            radius, width = (float(wheel[k].rstrip('fF')) * scale for k in ('radius', 'width'))
            inner, top = max(.35, x - width / 2 - .035), y + radius + .035
            if inner < half - .02 and top > floor + .02:
                wells.append(dict(z=round(z, 3), inner=round(inner, 3),
                                  halfLength=round(radius + .045, 3), top=round(top, 3)))
        assert len(wells) <= 1, (key, 'multiple axles need a larger clipping contract')
        if key in REAR_ARCH:
            inner, half_length, rise = REAR_ARCH[key]
            rear_wheel = info['wheels']['RearLeft']
            wells = [dict(z=round(rear_wheel[2] * scale - .06, 3), inner=inner,
                          halfLength=half_length, top=round(floor + rise, 3))]
        texture = 'fleet_' + key.lower()
        seats = ['MELensFurnitureLeft1', 'MELensFurnitureLeft2', 'MELensFurnitureRight1', 'MELensFurnitureRight2']
        narrow = half < .75
        if narrow:
            seats = seats[:2]
        # A narrow body cannot fit two opposing .55m furniture rows and a
        # .30m player. Put its kitchen across the front, with a rear-left
        # bed and an offset aisle instead of overlapping alternative slots.
        opening = dict(x=[round(-half-.04,3),round(half+.04,3)],
                       y=[round(floor-.02,3),round(ceiling+.02,3)],
                       z=[round(rear-.30,3),round(rear+.035,3)])
        hidden = {}
        # Matching bodies can have different factory interiors (the Payday van,
        # police equipment, extra benches). Inventory every variant's model keys.
        variant_parts = [part for name in row['vehicles'] for part in catalogue[name]['parts']]
        for part in variant_parts:
            for model in part['models']:
                mesh_name = model.get('mesh') or ''
                model_name = (model['file'] + ' ' + mesh_name).lower()
                part_name = part['id'].lower()
                glazing = 'window' in part_name or 'windshield' in part_name
                armor = 'armor' in part_name
                # Some variants name the model script InteriorExtra while the
                # FBX object is only swat_extra. Both names describe the model.
                # Cargo roof racks and window armor leave detached slivers when
                # cut at wall height; keep only their supported cab portion.
                if ('interior' in model_name or ((glazing or armor) and mesh_name)
                        or 'roofrack' in model_name):
                    hidden[model['file']] = {'plane': [0, -1, 0, round(visual_front / measure['mesh']['scale'], 4)]}
                if (glazing or armor) and ('rear' in part_name or 'back' in part_name):
                    # Rear glass can lose its door transform when the door is
                    # missing. Hide the whole cargo-only pane, not its old pose.
                    hidden[model['file']] = True
                if part['id'].startswith('Seat') and part['id'] not in ('SeatFrontLeft', 'SeatFrontRight'):
                    hidden[model['file']] = True
                elif ('seat' in mesh_name.lower() or 'bench' in mesh_name.lower()) and part['id'] not in ('SeatFrontLeft', 'SeatFrontRight'):
                    hidden[model['file']] = {'plane': [0, -1, 0, round(visual_front / measure['mesh']['scale'], 4)]}
                if 'stretcher' in (part['id'] + mesh_name).lower():
                    hidden[model['file']] = True
                if 'spare' in (part['id'] + mesh_name).lower():
                    # Cargo-roof spares obstruct the cutaway, but a spare on
                    # the intact cab roof must keep its original appearance.
                    hidden[model['file']] = {'plane': [0, -1, 0, round(visual_front / measure['mesh']['scale'], 4)]}
        # Some stock bodies embed their rear benches in the main body mesh.
        # Replace that interior geometry, keeping the factory floor and exterior.
        interior_box = dict(x=[round(-half + .015, 3), round(half - .015, 3)],
                            y=[round(floor + .018, 3), round(ceiling + .02, 3)],
                            z=[round(rear + .05, 3), round(front - .03, 3)])
        # Native seat rails and floor ribs cross the new floor inside the old
        # 18mm unclipped band. Remove that band only under the authored floor,
        # inset beyond its 30mm wall margin so the outer sill stays closed.
        floor_box = dict(x=[round(-half + .04, 3), round(half - .04, 3)],
                         y=[round(floor - .01, 3), round(floor + .025, 3)],
                         z=[round(rear + .04, 3), round(front - .04, 3)])
        spec = dict(key=key, vehicles=row['vehicles'], title=row['title'], kind='cargo',
                    measure=f'measure_{key}.json', scripts=row['scripts'], texture=texture,
                    reuseTexture='f700box', mesh=measure['mesh'], floorY=floor, ceiling=ceiling,
                    box=dict(x=half, z=[rear, front]), hide=hidden, clipBody=True, cutFront=front,
                    aisleX=-.25 if narrow else 0,
                    entry=dict(span=[-.70, .20] if narrow else [-.50, .50], wall='back',
                               part=row['entryDoor'], area='TruckBed', panelWall='right' if narrow else 'left'),
                    entryOpening=opening, windowBoxes=[interior_box, floor_box], openings=[], extraSeats=seats, wheelWells=wells,
                    vanillaSeats=sorted({p['id'] for p in info['passengers'] if '*' not in p['id']}),
                    waterTank=40, fuelTank=20, factoryLayout=True,
                    nativeBodyWalls=True,
                    nativeCabPartition=key != 'F350Ambulance',
                    separateShellSupports=True, separateDoorReturns=True,
                    spots=[
                        dict(wall='left', at=round(rear + .84 if narrow else front - .87, 3), length=1.50, depth=.55,
                             default='bed', empty=True, seats=seats[:2]),
                        dict(wall='front' if narrow else 'right', at=0 if narrow else round(front - .59, 3), length=1.0, depth=.55,
                             default='kitchen', empty=True),
                        dict(wall='front' if narrow else 'right', at=.26 if narrow else round(rear + .75, 3), length=.52, depth=.52,
                             default='fridge', empty=True),
                    ])
        if abs(measure['mesh']['lift']) < .00001:
            spec['modelShift'] = [0, 0, 0]
        if key == 'ChevyStepVan':
            spec['factoryEmpty'] = {'delivery': {'front': ['metalcase']}}
        if key in PLAIN_WALL_FAMILIES:
            spec['nativePlainFinish'] = True
            # The stock inward skin shares its authored partition's panel atlas.
            # Plain finish still selects the embedded stock glass/door contract.
            spec['nativeBodyLining'] = [.80, .77, .70]
            spec['nativeWallMaterial'] = 'f700box'
        if key in surface_cuts:
            spec['nativeSurfaceCuts'] = surface_cuts[key]['cuts']
        if key in ('E150Short', 'E150Long', 'E150Windows', 'F350Ambulance'):
            # Existing warm painted panels with fine seams and a dark metal
            # base, on the approved native hull rather than a new box shell.
            spec['nativeWallMaterial'] = 'b700'
        if key == 'ChevyStepVan':
            spec['nativeWallMaterial'] = 'f700box'
        if key in ('E150Short', 'E150Long', 'E150Windows'):
            # Fixed panels and solid living-area side leaves are separate
            # from the hull. Native Long and Short controls show the same
            # black inward skin on these aliases. AS empty-state originals also
            # identify the windowed side leaves' black lower panels. Their live
            # glass is separate; finish only the living-area physical leaves.
            # Cab doors remain outside this measured scope.
            spec['nativeBodyModels'] = ['86fordE150PanelLeft', '86fordE150PanelRight']
            living_leaves = sorted({model['file'] for name in row['vehicles']
                for part in catalogue[name]['parts'] if part['id'] in ('DoorRearLeft', 'DoorRearRight')
                for model in part['models'] if model['file'] in (
                    '86fordE150doorrl', '86fordE150doorrr', '86fordE150doorrlw', '86fordE150doorrrw')})
            spec['nativeBodyModels'].extend(living_leaves)
        if key in cab_partitions:
            # Visual closure clears the side leaf. Logical room, furnishing
            # anchors and navigation retain their original front.
            cap = cab_partitions[key]
            spec['cutFront'] = cap['cutFront']
            spec['cabBulkhead'] = cap['bulkhead']
            spec['navigationFront'] = front
            for part in variant_parts:
                if part['id'] == 'E150Divider':
                    for model in part['models']:
                        spec['hide'][model['file']] = True
                elif part['id'] in ('SeatFrontLeft', 'SeatFrontRight'):
                    for model in part['models']:
                        spec['hide'][model['file']] = {'plane': [0, -1, 0,
                            round((cap['bulkhead']['z'] + .006) / measure['mesh']['scale'], 4)]}
        if key == 'F350Ambulance':
            # Native transverse body faces reach z=-.4294016 behind cutFront
            # -.37. Cover them with 3.6mm clearance; the forward skin stays at
            # cutFront+.002 so its perimeter still seals the native cab.
            spec['cabBulkhead'] = dict(depth=.063)
            spec['cutFrontTop'] = 1.10  # keep the measured cab roof, cut the taller lightbar
            spec['factoryEmpty'] = {'medical': {'right': ['medlocker']}}
            # Native bulkhead rear face is z=-.4294017. The cabinet backs may
            # extend 14mm behind their anchors; 60mm rearward leaves 16mm clear.
            spec['factoryFrontInset'] = {'medical': .06}
            # Shared optional native API; geometry still requires per-family review.
            spec['flatWheelFloor'] = True
            # Numeric native-body measurements only; no dependency mesh is shipped.
            # overlap is a deliberate 3mm seam allowance.
            spec['nativeSupportSeals'] = dict(
                archSideX=1.06199999,
                archContour=[[-2.743421923,-.314921121],[-2.700385044,-.173418467],
                             [-2.578972176,-.021171647],[-2.403525708,.063318963],
                             [-2.208794828,.063318952],[-2.033348192,-.021171670],
                             [-1.911935324,-.173418478],[-1.868603402,-.314921163]],
                rearPlane=-3.871164697,rearSillTop=-.103415414,
                rearSpan=[-.885991598,.497893029],overlap=.003)
            # Closed native f350_door_rr measured in passenger space in Blender.
            spec['doorLinings'] = [dict(part='DoorRearRight',suffix='side_entry',box=dict(
                x=[-1.1,-.9],y=[floor-.02,ceiling+.02],z=[-1.713,-.981]),
                threshold=dict(innerX=-.95,outerX=-1.065,bottomY=-.315,thickness=.025))]
        elif key in ('F700Bank', 'F700Swat'):
            spec['nativeWallMaterial'] = 'f700box'
            spec['nativeCabPartition'] = True
            # The distinct armored cabs reach 1.295m and 1.142m respectively.
            spec['cutFrontTop'] = 1.33 if key == 'F700Bank' else 1.18
        if key == 'VanillaPassengerVan':
            # Source side-door vertices span z=-.5809..+.4577, with both
            # skins/upper returns at abs(x)=.6026..+.8191. Their lower panels share the fixed
            # side's blue/yellow mask: a window/door colour test cannot cut it.
            # Keep an 8mm jamb at each longitudinal end and the floor sill.
            spec['nativeDoorOpenings'] = [dict(part=part,x=x,
                y=[floor,ceiling+.02],z=[-.572,.448]) for part,x in (
                    ('DoorMiddleLeft',[.59,.84]),('DoorMiddleRight',[-.84,-.59]))]
        if not narrow:
            spec['spots'].insert(1, dict(wall='right', at=round(front - .87, 3), length=1.50, depth=.55,
                                         default='dinette', empty=True, seats=seats[2:]))
        # These measured renderer contracts are authored after the initial
        # catalogue expansion. Regenerating geometry must retain them.
        for field in ('nativeHighCut', 'nativeCeiling', 'nativeStockMetal',
                      'nativeWallBoundaryFinish', 'nativeRoofCuts',
                      'nativeEntryNearBounds', 'nativeArchTrimModels',
                      'nativeCabCutFront', 'nativeCabCutFrontTop'):
            if field in existing_spec:
                spec[field] = existing_spec[field]
        mv.apply_native_floor(spec)
        path = ROOT / f'tools-src/vehicles/specs/{key}.json'
        path.write_text(json.dumps(spec, indent=4) + '\n', encoding='utf-8', newline='\n')
        mv.build(str(path))
        suffixes = ['floor', 'walls', 'bulkhead', 'entry']+[d['suffix'] for d in spec.get('doorLinings',[])]
        if spec.get('separateShellSupports'):
            suffixes.append('support')
        if spec.get('nativeSupportSeals') and not spec['nativeSupportSeals'].get('archOnly'):
            suffixes.append('support_seals')
        if spec.get('flatWheelFloor'):
            suffixes += ['wheel_covers', 'wheel_floor', 'wheel_wall']
        if mv.separate_door_returns(spec):
            suffixes.append('door_returns')
        for suffix in suffixes:
            material = 'floor' if suffix in ('floor', 'wheel_floor', 'floor_perimeter') else 'walls'
            declarations.append(f'    model MELensShell_{texture}_{suffix} {{ mesh = vehicles/MELens_Fleet|shell_{texture}_{suffix}, texture = Vehicles/MELensShell_f700box_{material}, shader = vehiclewheel, scale = 0.0111111, }}')
        coverage.append(dict(family=key, title=row['title'], vehicles=row['vehicles'], dependencies=row['dependencies'],
                             representative=row['name'], mesh=info['model']['mesh']))
    assert not mv.PROBLEMS, '\n'.join(mv.PROBLEMS)
    declarations.append('}')
    (ROOT / 'mod/RealVehicleInteriors/common/media/scripts/MELens_fleet_models.txt').write_text('\n'.join(declarations) + '\n', encoding='utf-8', newline='\n')
    (ROOT / 'tools-src/vehicles/coverage.json').write_text(json.dumps(dict(families=coverage), indent=2) + '\n', encoding='utf-8', newline='\n')
    mv.write_native_models()
    mv.write_factory_models()
    print(f'Generated {len(rows)} measured families, {sum(len(r["vehicles"]) for r in rows)} vehicle definitions')


if __name__ == '__main__':
    main()
