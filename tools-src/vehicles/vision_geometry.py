"""Export sight openings from local measured bounds and resolved vehicle scripts.

Inputs are read-only numerical measurements produced by measure_vehicle.py and
pzscripts.py. Pass --floorplans for each directory containing those inputs.
No game/dependency models, textures or code are copied into the mod.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def export(roots):
    def read(name):
        for root in roots:
            path = root / name
            if path.is_file():
                return json.loads(path.read_text(encoding='utf-8-sig'))
        raise FileNotFoundError(name)

    specs = [json.loads(p.read_text(encoding='utf-8-sig'))
             for p in sorted((ROOT / 'tools-src/vehicles/specs').glob('*.json'))]
    specs.append(dict(key='FlyingCloud22', vehicles=['Base.Trailer54FlyingCloud22'],
                      measure='measure_FlyingCloud22.json', scripts=['campers.json', 'Trailer54FlyingCloud22']))
    families, count, fallback_count = [], 0, 0
    for spec in specs:
        if spec.get('disabled'):
            continue
        measure = read(spec['measure'])
        info = read(spec['scripts'][0])[spec['scripts'][1]]
        openings = []
        for part in info['parts']:
            ident = part['id']
            if '*' in ident:
                continue
            kind = 'window' if ident.startswith(('Window', 'Windshield')) else (
                'door' if ident.startswith('Door') or ident == 'TrunkDoor' else None)
            if not kind:
                continue
            found = []
            for model in part.get('models', []):
                mesh = (model.get('mesh') or '').rsplit('|', 1)[-1]
                bounds = measure['parts'].get(mesh)
                if not bounds:
                    continue
                # Part-model offsets are vehicle-space offsets, scaled by Loaded().
                # All current measured door/window models have zero local rotation.
                if any(abs(v) > .001 for v in (model.get('rotate') or [])):
                    raise ValueError(f"Unresolved rotated opening: {spec['key']} {ident} {mesh}")
                offset = model.get('offset') or [0, 0, 0]
                scale = info['model']['scale']
                x1, x2 = [bounds[k][0] + offset[0] * scale for k in ('min', 'max')]
                z1, z2 = [bounds[k][2] + offset[2] * scale for k in ('min', 'max')]
                # A single multi-pane window part can cover both sides. Keep the
                # two side strips separate, rather than opening the entire cabin.
                if kind == 'window' and x2 - x1 > 1 and z2 - z1 > 1.5:
                    found.extend([(x1, x1 + .12, z1, z2), (x2 - .12, x2, z1, z2)])
                else:
                    found.append((x1, x2, z1, z2))
            if not found:
                # Stock vehicles keep windows in the body model. Their own
                # interaction areas identify the applicable side and span.
                area_id = part.get('area')
                parent = part.get('parent')
                seen = set()
                while not area_id and parent and parent not in seen:
                    seen.add(parent)
                    owner = next((p for p in info['parts'] if p['id'] == parent), {})
                    area_id, parent = owner.get('area'), owner.get('parent')
                area = info['areas'].get(area_id)
                if area:
                    x, z, w, h = [v * info['model']['scale'] for v in area]
                    found.append((x - w / 2, x + w / 2, z - h / 2, z + h / 2))
                    fallback_count += 1
                elif kind == 'window':
                    raise ValueError(f"Unresolved window geometry: {spec['key']} {ident}")
            for bounds in found:
                openings.append([ident, kind, *[round(v, 4) for v in bounds]])
        families.append((spec['key'], spec['vehicles'], openings))
        count += len(spec['vehicles'])
    lines = ['-- Generated by tools-src/vehicles/vision_geometry.py from local numerical measurements.',
             '-- Horizontal openings use the same floor-level sight model as vanilla rooms.',
             'MELens = MELens or {}', 'MELens.VisionGeometry = {}', '']
    for key, vehicles, openings in families:
        rows = ';'.join(','.join(str(v) for v in row) for row in openings)
        lines.append(f'-- {key}')
        lines.append('local openings = ' + json.dumps(rows))
        for vehicle in vehicles:
            lines.append('MELens.VisionGeometry[' + json.dumps(vehicle) + '] = openings')
        lines.append('')
    target = ROOT / 'mod/RealVehicleInteriors/common/media/lua/shared/MELens_VisionGeometry.lua'
    # Runtime scripts preserve their bytes in Git; keep this export identical on
    # Windows and Unix rather than inheriting the host's newline conversion.
    target.write_text('\n'.join(lines), encoding='utf-8', newline='\r\n')
    print(json.dumps(dict(families=len(families), vehicles=count, stockAreaOpenings=fallback_count,
                          output=str(target))))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--floorplans', type=Path, action='append', required=True)
    args = parser.parse_args()
    export(args.floorplans)
